#!/usr/bin/env node
/**
 * Copies the notification wording into the Edge Functions, where Deno can import it.
 *
 * `packages/shared/src/notifications.ts` is the one place a notification is worded, and
 * push must say exactly what the inbox says. The Deno function cannot import it where it
 * lives: Deno needs an extension on every import (`./order-status` is not one) and
 * `supabase functions deploy` bundles from `supabase/functions`. So this writes a copy
 * into `_shared/`, the way `db:types` writes `database.types.ts`: generated, never
 * edited, and checked by `supabase/test/push.test.ts`, which fails if the copy is stale.
 *
 *   npm run functions:sync
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = fileURLToPath(new URL('../packages/shared/src/notifications.ts', import.meta.url));
const TARGET = fileURLToPath(
  new URL('../supabase/functions/_shared/notifications.generated.ts', import.meta.url),
);

const IMPORT = "import type { OrderStatus } from './order-status';";

const HEADER = `// GENERATED by scripts/sync-function-shared.mjs from packages/shared/src/notifications.ts.
// Do not edit. Change the source and run \`npm run functions:sync\`; a test fails otherwise.

// Deno cannot follow the source's extensionless import, and a status the database stores
// is a string anyway. The source keeps the precise union for the apps.
type OrderStatus = string;`;

/** The generated file's exact contents, from the source's. Exported for the drift test. */
export function generate(source) {
  if (!source.includes(IMPORT)) {
    throw new Error(`expected ${IMPORT} in notifications.ts -- update the generator`);
  }
  return source.replace(IMPORT, HEADER);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(TARGET, generate(readFileSync(SOURCE, 'utf8')));
  console.log('wrote supabase/functions/_shared/notifications.generated.ts');
}
